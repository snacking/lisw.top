CREATE TABLE IF NOT EXISTS lisw_endpoints (
 id VARCHAR(64) NOT NULL PRIMARY KEY,
 name VARCHAR(128) NOT NULL,
 address VARCHAR(253) NOT NULL UNIQUE,
 address_type ENUM('ipv4','ipv6','hostname') NOT NULL,
 region VARCHAR(128) NOT NULL DEFAULT '',
 provider VARCHAR(64) NOT NULL DEFAULT '',
 owner_user_id VARCHAR(64) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_lisw_endpoint_owner FOREIGN KEY(owner_user_id) REFERENCES lisw_users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
